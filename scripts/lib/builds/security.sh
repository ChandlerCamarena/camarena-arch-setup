#!/usr/bin/env bash
# security.sh - build-from-source steps for the security profile.
# Sourced by 02-build-from-source.sh, not executed directly; expects
# common.sh and sources.sh.

BURP_INSTALL_DIR="$HOME/.local/opt/burpsuite"
BURP_URL="https://portswigger.net/burp/releases/download?product=community&type=linux"

METASPLOIT_SRC_DIR="$HOME/.local/src/metasploit-framework"
METASPLOIT_BUILD_MARKER="$METASPLOIT_SRC_DIR/.last-built-commit"

build_burpsuite() {
    if [[ -d "$BURP_INSTALL_DIR" ]]; then
        log "Burp Suite Community already installed at $BURP_INSTALL_DIR, skipping"
        return 0
    fi

    log "Downloading Burp Suite Community installer (latest)..."
    local tmp_installer
    tmp_installer="$(mktemp --suffix=.sh)"
    curl -fsSL "$BURP_URL" -o "$tmp_installer"
    chmod +x "$tmp_installer"

    log "Running Burp Suite installer in unattended mode, installing to $BURP_INSTALL_DIR..."
    # The installer registers burp:// handlers by writing ~/.config/mimeapps.list,
    # which belongs to this repo (05-dotfiles-copy.sh) and would otherwise be
    # backed up and overwritten there. Put back whatever was there before.
    local mimeapps="$HOME/.config/mimeapps.list" saved
    saved="$(mktemp)"
    [[ -f "$mimeapps" ]] && cp "$mimeapps" "$saved"
    # install4j installer: -q = unattended, -dir = target install path
    "$tmp_installer" -q -dir "$BURP_INSTALL_DIR"
    if [[ -s "$saved" ]]; then cp "$saved" "$mimeapps"; else rm -f "$mimeapps"; fi
    rm -f "$tmp_installer" "$saved"
    log "Burp Suite Community installed to $BURP_INSTALL_DIR"
}

build_metasploit() {
    # Rapid7's omnibus installer (msfinstall) only supports .deb/.rpm systems;
    # building from source with Bundler is their documented fallback.
    local pin
    pin="$(source_get metasploit pin)"
    if [[ "$(cat "$METASPLOIT_BUILD_MARKER" 2>/dev/null)" == "$pin" ]]; then
        log "Metasploit already at pinned ${pin:0:12}."
        return 0
    fi

    source_checkout metasploit "$METASPLOIT_SRC_DIR"

    # Gems go into the checkout (vendor/bundle), not the system gem dir,
    # which isn't writable without root
    log "Installing Metasploit's gems with Bundler (ruby, ruby-bundler from the security profile)..."
    (
        cd "$METASPLOIT_SRC_DIR" || exit 1
        bundle config set --local path vendor/bundle
        bundle config set --local without 'development test coverage'
        bundle install --jobs "$(nproc)"
    )

    # Real commands on PATH instead of "cd there and bundle exec"
    mkdir -p "$HOME/.local/bin"
    local cmd
    for cmd in msfconsole msfvenom msfdb; do
        cat > "$HOME/.local/bin/$cmd" <<EOF
#!/usr/bin/env bash
# Generated by scripts/lib/builds/security.sh
exec env BUNDLE_GEMFILE="$METASPLOIT_SRC_DIR/Gemfile" bundle exec "$METASPLOIT_SRC_DIR/$cmd" "\$@"
EOF
        chmod +x "$HOME/.local/bin/$cmd"
    done

    echo "$pin" > "$METASPLOIT_BUILD_MARKER"
    log "Metasploit ${pin:0:12} ready: msfconsole, msfvenom, msfdb in ~/.local/bin (first run: msfdb init)."
}

run_security_builds() {
    log "Running security profile build-from-source steps..."
    build_burpsuite
    build_metasploit
}

#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/lib/common.sh"

require_not_root

CONFIG_SRC="$SCRIPT_DIR/../config"

begin_managed

log "Setting system-wide ZDOTDIR..."
if ! grep -q 'ZDOTDIR' /etc/zsh/zshenv 2>/dev/null; then
    echo 'export ZDOTDIR="$HOME/.config/zsh"' | sudo tee -a /etc/zsh/zshenv
fi

# Login shell too, not just kitty's `shell zsh`: TTYs, ssh and anything else
# that starts your login shell get the same environment.
if [[ "$(getent passwd "$USER" | cut -d: -f7)" != /usr/bin/zsh ]]; then
    log "Making zsh the login shell for $USER..."
    sudo chsh -s /usr/bin/zsh "$USER"
fi

# Whole directories: a new file under config/<dir>/ deploys without an
# edit here, and one removed from the repo is pruned (prune_managed below).
# Executable bits come from git.
CONFIG_DIRS=(quickshell hypr kitty nvim rofi Thunar gtk-3.0 gtk-4.0)
log "Copying config directories: ${CONFIG_DIRS[*]}..."
for dir in "${CONFIG_DIRS[@]}"; do
    copy_plain "$CONFIG_SRC/$dir/." "$HOME/.config/$dir"
done

log "Copying rices (theme.json + wallpaper.png per rice, plus switch.sh)..."
copy_plain "$CONFIG_SRC/rices/." "$HOME/.config/rices"

if command_exists openrgb; then
    log "Copying RGB config (declarative OpenRGB profiles, see config/rgb/rgb.py)..."
    copy_plain "$CONFIG_SRC/rgb/rgb.py"                   "$HOME/.config/rgb/rgb.py"
    copy_plain "$CONFIG_SRC/rgb/profiles/."               "$HOME/.config/rgb/profiles"
    copy_plain "$CONFIG_SRC/rgb/rgb"                      "$HOME/.local/bin/rgb"
    copy_plain "$CONFIG_SRC/systemd/user/openrgb.service" "$HOME/.config/systemd/user/openrgb.service"
    if [[ ! -x "$HOME/.config/rgb/venv/bin/python" ]]; then
        log "Creating RGB venv with openrgb-python (not packaged in official repos)..."
        python -m venv "$HOME/.config/rgb/venv"
        "$HOME/.config/rgb/venv/bin/pip" install --quiet openrgb-python
    fi
else
    log "openrgb not installed, skipping RGB config."
fi

copy_plain "$CONFIG_SRC/mimeapps.list" "$HOME/.config/mimeapps.list"
copy_plain "$CONFIG_SRC/git/."         "$HOME/.config/git"
copy_plain "$CONFIG_SRC/zsh/."         "$HOME/.config/zsh"

# Pinned in packages/sources.txt. A plain checkout instead of oh-my-zsh's
# installer: the installer always fetches master, and .zshrc is ours anyway.
log "Checking out oh-my-zsh and powerlevel10k at their pinned commits..."
source "$SCRIPT_DIR/lib/sources.sh"
source_checkout ohmyzsh       "$HOME/.config/zsh/ohmyzsh"
source_checkout powerlevel10k "$HOME/.config/zsh/ohmyzsh/custom/themes/powerlevel10k"

mkdir -p "$HOME/.config/yazi"

# Keep whichever rice is active across updates; retrowave on a fresh install
# or if the active one was removed from the repo.
RICES="$HOME/.config/rices"
ACTIVE_RICE="$(cat "$RICES/.active" 2>/dev/null || true)"
[[ -f "$RICES/$ACTIVE_RICE/theme.json" ]] || ACTIVE_RICE=retrowave

# Before switch.sh turns these into symlinks: an older install copied
# them as plain files, and local edits there shouldn't vanish silently.
for live in "$HOME/.config/hypr/theme.json:theme.json" \
            "$HOME/.config/hypr/wallpapers/wallpaper.png:wallpaper.png"; do
    dest="${live%%:*}"
    if [[ -f "$dest" && ! -L "$dest" ]] && ! cmp -s "$dest" "$RICES/$ACTIVE_RICE/${live#*:}"; then
        backup_if_exists "$dest"
    fi
done

log "Activating rice '$ACTIVE_RICE' and running theme generators..."
bash "$RICES/scripts/switch.sh" --no-reload "$ACTIVE_RICE"


log "Provisioning Vivaldi config..."
VIVALDI_PROFILE_DIR="$HOME/.config/vivaldi/Default"

if [[ -f "$VIVALDI_PROFILE_DIR/Preferences" ]]; then
    log "Live Vivaldi profile already exists at $VIVALDI_PROFILE_DIR, skipping seed (would clobber cookies/sessions/history)."
else
    if [[ -f "$CONFIG_SRC/vivaldi/Preferences" ]]; then
        log "No existing Vivaldi profile found, seeding tracked Preferences..."
        mkdir -p "$VIVALDI_PROFILE_DIR"
        cp "$CONFIG_SRC/vivaldi/Preferences" "$VIVALDI_PROFILE_DIR/Preferences"
        if [[ -f "$CONFIG_SRC/vivaldi/Bookmarks" ]]; then
            cp "$CONFIG_SRC/vivaldi/Bookmarks" "$VIVALDI_PROFILE_DIR/Bookmarks"
        fi
        log "Vivaldi config seeded. protection.macs will be regenerated by Vivaldi on first launch."
    else
        log "No tracked Vivaldi config in repo yet (config/vivaldi/Preferences), skipping seed."
    fi
fi

VIVALDI_EXT_LIST="$CONFIG_SRC/vivaldi/extensions.txt"
if [[ -f "$VIVALDI_EXT_LIST" ]]; then
    mapfile -t vivaldi_extensions < <(grep -vE '^\s*#|^\s*$' "$VIVALDI_EXT_LIST" | awk '{print $1}')
    if [[ ${#vivaldi_extensions[@]} -gt 0 ]]; then
        log "Force-installing ${#vivaldi_extensions[@]} Vivaldi extension(s) via policy..."
        sudo mkdir -p /etc/vivaldi/policies/managed
        forcelist_json="{\"ExtensionInstallForcelist\": ["
        for i in "${!vivaldi_extensions[@]}"; do
            ext="${vivaldi_extensions[$i]}"
            forcelist_json+="\"${ext};https://clients2.google.com/service/update2/crx\""
            if [[ $i -lt $((${#vivaldi_extensions[@]} - 1)) ]]; then
                forcelist_json+=","
            fi
        done
        forcelist_json+="]}"
        echo "$forcelist_json" | sudo tee /etc/vivaldi/policies/managed/extensions.json > /dev/null
        log "Extension policy written to /etc/vivaldi/policies/managed/extensions.json (applies next Vivaldi launch)."
    fi
else
    log "No $VIVALDI_EXT_LIST found, skipping extension force-install."
fi
log "Removing dotfiles the repo no longer ships..."
prune_managed

log "Dotfiles copy stage complete."
